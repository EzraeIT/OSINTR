def _entity_tag(case: dict) -> str:
    ent = (case or {}).get("entity") or {}
    cj, vi = ent.get("cnpj"), ent.get("vies")
    name = (cj or {}).get("name") or (vi or {}).get("name")
    num = ent.get("query", {}).get("vat")
    if name and num:
        return f"{name} ({num})"
    return name or num or ""


def build_network_case(entries, correlations, *, analyst: str = "", lang: str = "it") -> dict:
    """entries: lista di (target, tipo, dati grezzi di scan_*, caso forense osintr_ext o None).
    correlations: output di osint_recon.find_correlations() - [{'type','value','strength','targets'}, ...]."""
    T = S.get(lang, S["it"])
    type_label = TYPE_LABEL_IT if lang == "it" else TYPE_LABEL_EN
    targets = []
    for target, ttype, data, case in entries:
        if case:
            lvl = (case.get("assessment") or {}).get("level", "n/d")
            wallets = len(case.get("wallets", []))
            vat_tag = _entity_tag(case)
            note_bits = [f"{lvl.upper()}"]
            if vat_tag:
                note_bits.append(vat_tag)
            if wallets:
                note_bits.append(f"{wallets} wallet")
            note = " - ".join(note_bits)
        else:
            lvl = None
            note = T["no_risk"]
        targets.append({"target": target, "type": ttype, "type_label": type_label.get(ttype, ttype),
                        "level": lvl, "note": note})

    shared = [{"kind": c["type"], "value": c["value"], "strength": c.get("strength", "weak"),
              "targets": sorted(c["targets"])} for c in correlations]

    return {"meta": {"analyst": analyst, "lang": lang, "generated": datetime.now(timezone.utc).isoformat(),
                     "tool_version": VERSION},
            "targets": targets, "shared": shared}


def render_network_report(network_case: dict, path: str, lang: str = "it") -> str:
    T = S.get(lang, S["it"])
    strength_label = STRENGTH_LABEL.get(lang, STRENGTH_LABEL["it"])
    targets = network_case["targets"]
    shared = network_case["shared"]
    analyst = network_case["meta"].get("analyst") or ""
    today = date.today().isoformat()

    styles = {
        "h1": ParagraphStyle("h1", fontName="Helvetica-Bold", fontSize=13, textColor=NAVY, spaceBefore=12,
                             spaceAfter=6, keepWithNext=1),
        "body": ParagraphStyle("body", fontName="Helvetica", fontSize=9, leading=12.5, textColor=colors.black),
        "small": ParagraphStyle("small", fontName="Helvetica-Oblique", fontSize=7.5, leading=10, textColor=GREY),
        "cell": ParagraphStyle("cell", fontName="Helvetica", fontSize=8, leading=10.5),
        "cellb": ParagraphStyle("cellb", fontName="Helvetica-Bold", fontSize=8, leading=10.5),
        "mono": ParagraphStyle("mono", fontName="Courier", fontSize=7.3, leading=9.5),
    }

    def P(text, style="body"):
        return Paragraph(escape(str(text)), styles[style])

    def table(rows, widths):
        t = Table(rows, colWidths=widths, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, 0), 8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cccccc")),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
            ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3), ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5)]))
        return t

    story = []
    story.append(Paragraph(T["title"], ParagraphStyle("title", fontName="Helvetica-Bold", fontSize=14, textColor=NAVY)))
    story.append(P(T["subtitle"].format(n=len(targets))))
    story.append(P(T["version"].format(d=today, a=analyst or T["na"]), "small"))
    story.append(Spacer(1, 10))

    story.append(Paragraph(T["targets_title"], styles["h1"]))
    rows = [[P(c, "cellb") for c in T["targets_cols"]]]
    for t in targets:
        if t["level"]:
            lvl_txt = f'<font color="{LEVEL_HEX.get(t["level"], "#555555")}"><b>{t["level"].upper()}</b></font>'
            lvl_cell = Paragraph(lvl_txt, styles["cell"])
        else:
            lvl_cell = P(T["na"], "cell")
        rows.append([P(t["target"], "cell"), P(t["type_label"], "cell"), lvl_cell, P(t["note"], "cell")])
    story.append(table(rows, [48 * mm, 22 * mm, 22 * mm, 78 * mm]))

    story.append(Paragraph(T["shared_title"], styles["h1"]))
    story.append(P(T["shared_intro"], "small"))
    story.append(Spacer(1, 3))
    if shared:
        rows = [[P(c, "cellb") for c in T["shared_cols"]]]
        for sh in sorted(shared, key=lambda x: (x["strength"] != "strong", x["kind"], x["value"])):
            val = short(sh["value"]) if "wallet" in sh["kind"].lower() else sh["value"]
            rows.append([P(sh["kind"], "cell"), P(val, "mono"), P(strength_label.get(sh["strength"], sh["strength"]), "cell"),
                        P(", ".join(sh["targets"]), "cell")])
        story.append(table(rows, [34 * mm, 48 * mm, 22 * mm, 66 * mm]))
    else:
        story.append(P(T["none_shared"]))

    story.append(Paragraph(T["detail_title"], styles["h1"]))
    story.append(P(T["detail_note"], "small"))

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 6.8)
        canvas.setFillColor(GREY)
        canvas.drawString(18 * mm, 10 * mm, T["footer"].format(v=VERSION, d=today))
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, str(doc.page))
        canvas.restoreState()

    doc = SimpleDocTemplate(path, pagesize=A4, topMargin=18 * mm, bottomMargin=16 * mm,
                            leftMargin=16 * mm, rightMargin=16 * mm, title=T["title"])
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return path
